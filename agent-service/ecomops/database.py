"""Operations persistence. Medusa owns commerce tables and transactions."""
import os
import sqlite3
from contextlib import contextmanager
from pathlib import Path


class PostgresConnection:
    """Use the common operations SQL subset with a PostgreSQL connection."""

    def __init__(self, connection):
        self.connection = connection

    def execute(self, sql, params=()):
        return self.connection.execute(sql.replace('?', '%s'), params)

    def executemany(self, sql, params):
        with self.connection.cursor() as cursor:
            cursor.executemany(sql.replace('?', '%s'), params)

    def __enter__(self):
        return self

    def __exit__(self, exc_type, exc, traceback):
        if exc_type:
            self.connection.rollback()
        else:
            self.connection.commit()

    def close(self):
        self.connection.close()


def open_db(read_only=False):
    url = os.environ.get('ECOMOPS_DATABASE_URL')
    if url:
        import psycopg
        from psycopg import IsolationLevel
        from psycopg.rows import dict_row

        connection = psycopg.connect(url, row_factory=dict_row, connect_timeout=5,
                                     options='-c search_path=ecomops_agent,pg_catalog')
        connection.isolation_level = IsolationLevel.READ_COMMITTED
        db = PostgresConnection(connection)
        if read_only:
            db.execute('SET TRANSACTION READ ONLY')
        return db
    path = Path(os.environ.get('ECOMOPS_AUDIT_DB', '.runtime/audit.sqlite3'))
    if read_only:
        db = sqlite3.connect(path.resolve().as_uri() + '?mode=ro', uri=True)
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        db = sqlite3.connect(path)
    db.row_factory = sqlite3.Row
    return db


@contextmanager
def connect_read_only():
    db = open_db(read_only=True)
    try:
        yield db
    finally:
        db.close()


def create_schema(db):
    postgres = isinstance(db, PostgresConnection)
    sequence = 'BIGINT GENERATED BY DEFAULT AS IDENTITY' if postgres else 'INTEGER'
    if postgres:
        db.execute("SELECT pg_advisory_xact_lock(hashtext('ecomops_agent_schema'))")
        db.execute('CREATE SCHEMA IF NOT EXISTS ecomops_agent')
    db.execute('CREATE TABLE IF NOT EXISTS proposals '
               '(id TEXT PRIMARY KEY, run_id TEXT, payload TEXT, status TEXT, receipt TEXT)')
    db.execute("""CREATE TABLE IF NOT EXISTS receipt_batches (
        proposal_id TEXT NOT NULL, request_id TEXT NOT NULL, quantity INTEGER NOT NULL,
        status TEXT NOT NULL, receipt TEXT NOT NULL, PRIMARY KEY (proposal_id, request_id)
    )""")
    db.execute(f"""CREATE TABLE IF NOT EXISTS audit_events (
        sequence {sequence} PRIMARY KEY, actor TEXT NOT NULL, role TEXT NOT NULL,
        action TEXT NOT NULL, subject TEXT NOT NULL, note TEXT, occurred_at TEXT NOT NULL
    )""")
    db.execute("""CREATE INDEX IF NOT EXISTS audit_receipt_reconcile
                  ON audit_events (subject, sequence DESC) WHERE action='reconciled'""")
    db.execute("""CREATE TABLE IF NOT EXISTS inventory_observations (
        inventory_item_id TEXT NOT NULL, location_id TEXT NOT NULL,
        observed_at TEXT NOT NULL, sku TEXT, stocked TEXT NOT NULL,
        reserved TEXT NOT NULL, available TEXT NOT NULL,
        PRIMARY KEY (inventory_item_id, location_id, observed_at)
    )""")
    db.execute("""CREATE INDEX IF NOT EXISTS inventory_history_sku_location
                  ON inventory_observations (sku, location_id, observed_at)""")
    db.execute("""CREATE TABLE IF NOT EXISTS order_alerts (
        id TEXT PRIMARY KEY, payload TEXT NOT NULL, status TEXT NOT NULL
    )""")
    db.execute(f"""CREATE TABLE IF NOT EXISTS order_alert_events (
        sequence {sequence} PRIMARY KEY, alert_id TEXT NOT NULL,
        status TEXT NOT NULL, occurred_at TEXT NOT NULL
    )""")
    db.execute("""CREATE TABLE IF NOT EXISTS daily_reports (
        day TEXT NOT NULL, zone TEXT NOT NULL, payload TEXT NOT NULL,
        generated_at TEXT NOT NULL, PRIMARY KEY (day, zone)
    )""")
    db.execute("""CREATE TABLE IF NOT EXISTS order_alert_scan_jobs (
        id TEXT PRIMARY KEY, claim TEXT, state TEXT NOT NULL, next_run_at TEXT NOT NULL,
        lease_until TEXT, started_at TEXT, finished_at TEXT, failure_count INTEGER NOT NULL,
        alert_count INTEGER, error TEXT
    )""")
    db.execute("""CREATE TABLE IF NOT EXISTS report_jobs (
        day TEXT NOT NULL, zone TEXT NOT NULL, claim TEXT NOT NULL,
        state TEXT NOT NULL, PRIMARY KEY (day, zone)
    )""")


def repair_unresolved_receipts(db):
    # Earlier versions could close a receipt without a verified disposition.
    unknown = '{"outcome": "unknown"}'
    unresolved = """
        SELECT p.id FROM proposals p WHERE p.status='reconciled' AND (
            EXISTS (SELECT 1 FROM receipt_batches b
                    WHERE b.proposal_id=p.id AND b.status='reconciled' AND b.receipt=?)
            OR EXISTS (
                SELECT 1 FROM audit_events a
                WHERE a.sequence=(SELECT max(previous.sequence) FROM audit_events previous
                                  WHERE previous.subject=p.id AND previous.action='reconciled')
                  AND substr(COALESCE(a.note, ''), 1, length('Outcome received: ')) <> 'Outcome received: '
                  AND substr(COALESCE(a.note, ''), 1, length('Outcome not_received: ')) <> 'Outcome not_received: '
            )
        )
    """
    if db.execute(f'{unresolved} LIMIT 1', (unknown,)).fetchone() is None:
        return
    db.execute(f"UPDATE proposals SET status='needs_review' WHERE id IN ({unresolved})", (unknown,))
    db.execute("""
        UPDATE receipt_batches SET status='needs_review' WHERE status='reconciled' AND receipt=?
          AND proposal_id IN (SELECT id FROM proposals WHERE status='needs_review')
    """, (unknown,))


def connect():
    db = open_db()
    try:
        with db:
            create_schema(db)
            repair_unresolved_receipts(db)
    except Exception:
        db.close()
        raise
    return db


@contextmanager
def transaction():
    db = connect()
    try:
        with db:
            yield db
    finally:
        db.close()


def claim_receipt(db, proposal_id, item, location, status='approved', prior_receipt=None):
    if isinstance(db, PostgresConnection):
        db.execute('SELECT pg_advisory_xact_lock(hashtext(?), hashtext(?))', (item, location))
        item_sql = "pending.payload::jsonb->>'inventory_item_id'"
        location_sql = "pending.payload::jsonb->>'location_id'"
    else:
        item_sql = "json_extract(pending.payload, '$.inventory_item_id')"
        location_sql = "json_extract(pending.payload, '$.location_id')"
    prior_filter = 'receipt IS NULL' if prior_receipt is None else 'receipt=?'
    parameters = [proposal_id, status]
    if prior_receipt is not None:
        parameters.append(prior_receipt)
    parameters.extend([item, location])
    return db.execute(f"""
        UPDATE proposals SET status='applying'
        WHERE id=? AND status=? AND {prior_filter} AND NOT EXISTS (
            SELECT 1 FROM proposals AS pending
            WHERE pending.status IN ('applying', 'needs_review')
            AND {item_sql}=? AND {location_sql}=?
        )
    """, parameters).rowcount
